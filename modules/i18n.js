export function getLanguage() {
  const stored = String(localStorage.getItem(LANG_KEY) || "en").toLowerCase();
  return SUPPORTED.includes(stored) ? stored : "en";
}

export function setLanguage(lang) {
  const next = SUPPORTED.includes(String(lang).toLowerCase()) ? String(lang).toLowerCase() : "en";
  localStorage.setItem(LANG_KEY, next);
  document.documentElement.setAttribute("lang", next === "el" ? "el" : "en");
  document.documentElement.setAttribute("data-lang", next);
  window.dispatchEvent(new CustomEvent("exact:langChanged", { detail: { lang: next } }));
  applyI18n(document);
  return next;
}

export function t(key, fallback = "") {
  const lang = getLanguage();
  return (dict[lang] && dict[lang][key]) || (dict.en && dict.en[key]) || fallback || key;
}

export function applyI18n(root = document) {
  const scope = root || document;
  scope.querySelectorAll?.("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key, el.textContent || "");
  });
  scope.querySelectorAll?.("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key, el.getAttribute("placeholder") || ""));
  });
  scope.querySelectorAll?.("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.setAttribute("title", t(key, el.getAttribute("title") || ""));
  });
  updateLanguageToggle();
}

function updateLanguageToggle() {
  const lang = getLanguage();
  document.querySelectorAll("[data-lang-choice]").forEach((btn) => {
    const val = btn.getAttribute("data-lang-choice");
    btn.classList.toggle("active", val === lang);
    btn.setAttribute("aria-pressed", val === lang ? "true" : "false");
  });
}

export function initLanguageToggle() {
  document.documentElement.setAttribute("lang", getLanguage() === "el" ? "el" : "en");
  document.documentElement.setAttribute("data-lang", getLanguage());
  document.querySelectorAll("[data-lang-choice]").forEach((btn) => {
    if (btn.dataset.i18nBound === "1") return;
    btn.addEventListener("click", () => setLanguage(btn.getAttribute("data-lang-choice") || "en"));
    btn.dataset.i18nBound = "1";
  });
  applyI18n(document);
}

